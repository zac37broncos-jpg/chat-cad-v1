export function buildNotices(lock, nodeModulesRoot = root) {
  const pkgs = productionPackages(lock);
  const head = [
    'CHAD third-party notices',
    '========================',
    '',
    'CHAD uses the open-source software listed below. Each package keeps its own licence; the',
    'licence text follows each entry. Generated by scripts/third-party-notices.mjs from',
    'package-lock.json; do not edit by hand.',
    '',
    `${pkgs.length} packages:`,
    ...pkgs.map((p) => `  ${p.name} ${p.version}  (${p.license ?? 'see licence text'})`),
    '',
    UPSTREAM,
  ];
  const body = pkgs.map((p) => {
    const text = licenceText(join(nodeModulesRoot, p.path));
    return [`----------------------------------------------------------------------`, `${p.name} ${p.version}`, `Licence: ${p.license ?? 'unknown'}`, '', text ?? `(No licence file is shipped in this package; its declared licence is ${p.license ?? 'unknown'}.)`, ''].join('\n');
  });
  return head.join('\n') + '\n' + body.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  const text = buildNotices(lock);
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('public/THIRD_PARTY_NOTICES.txt is out of date: run node scripts/third-party-notices.mjs'); process.exit(1); }
    console.log('THIRD_PARTY_NOTICES.txt is up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
