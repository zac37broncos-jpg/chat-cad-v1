#!/usr/bin/env node
/**
 * Writes public/THIRD_PARTY_NOTICES.txt: every third-party package CHAD runs on the user's computer
 * (the production dependency tree in package-lock.json), with its licence name and full licence text,
 * plus the upstream notices for code compiled into the two WebAssembly modules.
 *
 * Vite serves public/ as-is, so the file is reachable in the app at /THIRD_PARTY_NOTICES.txt
 * (Options > About CHAD links to it) and ships inside every production build.
 *
 *   node scripts/third-party-notices.mjs          write the file
 *   node scripts/third-party-notices.mjs --check  exit 1 if the file is out of date (tests/legal.test.ts runs this)
 *
 * Why: MIT, BSD and ISC require their copyright notice in copies; LGPL-2.1 section 6 requires a
 * prominent notice that the library is used plus a copy of the licence (docs/LICENSES.md).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'public', 'THIRD_PARTY_NOTICES.txt');

/** Production packages (not dev-only) from the lockfile, sorted by name. */
export function productionPackages(lock) {
  const out = [];
  const seen = new Set();
  for (const [path, meta] of Object.entries(lock.packages)) {
    if (!path || meta.dev || meta.devOptional || meta.optional) continue;
    const name = path.replace(/^.*node_modules\//, '');
    if (seen.has(`${name}@${meta.version}`)) continue; // the same version installed in several places
    seen.add(`${name}@${meta.version}`);
    out.push({ name, path, version: meta.version, license: meta.license });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function licenceText(dir) {
  if (!existsSync(dir)) return null;
  const f = readdirSync(dir).filter((n) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(n)).sort();
  if (!f.length) return null;
  return f.map((n) => readFileSync(join(dir, n), 'utf8').replace(/\r\n/g, '\n').trim()).join('\n\n');
}

